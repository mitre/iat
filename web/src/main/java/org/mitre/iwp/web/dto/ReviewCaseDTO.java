package org.mitre.iwp.web.dto;

import java.util.Date;
import java.util.List;

public class ReviewCaseDTO {
    public ReviewCaseDTO(){}

    public ReviewCaseDTO(Long id, String title, String description, String priority, Date dueDate, Date createdDate, String createdBy, Date modifiedDate, String modifiedBy, List<String> tags, boolean isWholeCaseCompleted) {
        this.id = id;
        this.title = title;
        this.description = description;
        this.priority = priority;
        this.dueDate = dueDate;
        this.createdDate = createdDate;
        this.createdBy = createdBy;
        this.modifiedDate = modifiedDate;
        this.modifiedBy = modifiedBy;
        this.tags = tags;
        this.isWholeCaseCompleted = isWholeCaseCompleted;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getPriority() {
        return priority;
    }

    public void setPriority(String priority) {
        this.priority = priority;
    }

    public Date getDueDate() {
        return dueDate;
    }

    public void setDueDate(Date dueDate) {
        this.dueDate = dueDate;
    }

    public Date getCreatedDate() {
        return createdDate;
    }

    public void setCreatedDate(Date createdDate) {
        this.createdDate = createdDate;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(String createdBy) {
        this.createdBy = createdBy;
    }

    public Date getModifiedDate() {
        return modifiedDate;
    }

    public void setModifiedDate(Date modifiedDate) {
        this.modifiedDate = modifiedDate;
    }

    public String getModifiedBy() {
        return modifiedBy;
    }

    public void setModifiedBy(String modifiedBy) {
        this.modifiedBy = modifiedBy;
    }

    public List<String> getTags() {
        return tags;
    }

    public void setTags(List<String> tags) {
        this.tags = tags;
    }

    public boolean getIsWholeCaseCompleted() {
        return isWholeCaseCompleted;
    }

    public void setIsWholeCaseCompleted(boolean wholeCaseCompleted) {
        isWholeCaseCompleted = wholeCaseCompleted;
    }

    Long id;
    String title;
    String description;
    String priority;
    Date dueDate;
    Date createdDate;
    String createdBy;
    Date modifiedDate;
    String modifiedBy;
    List<String> tags;
    boolean isWholeCaseCompleted;
}
